"""Random stress test: 500 seeded random days, both disruption kinds.

Checks that the hard rules (PTVR = 0, no overlaps, gate respected, ≤ 50%
compression) ALWAYS hold. The generator is a bit-exact port of the Node
stress test (mulberry32, same seed, same call order), so these are the SAME 500
days the Node engine was tested on; test_same_days_as_node proves it. These
inputs are test fixtures, not research data.
"""
import hashlib
import json
from typing import Any, Callable

from components.c1_disruption.engine.mvd import generate_mvd
from components.c1_disruption.engine.time import to_hhmm
from components.c1_disruption.tests.engine.invariants import compute_ptvr, find_violations

SEED = 20261007
DAYS = 500
# sha256 of the 500 days generated by the Node stress test (keys sorted, compact
# JSON), computed from anchor-ai-component1 on 13 Oct 2026.
NODE_DAYS_SHA256 = "3aea26f967cfc67d5e45d1d8fb76be830311f1d5f175d93fbc1e3186d44c9f9d"

_U32 = 0xFFFFFFFF


def seeded_random(seed: int) -> Callable[[], float]:
    """mulberry32, as in the Node test: floats in [0, 1).

    JS works on 32-bit integers (|0, >>>, Math.imul); here every value is kept as
    an unsigned 32-bit int, which has the same bits, so the sequence is identical.
    """
    a = seed & _U32

    def next_float() -> float:
        nonlocal a
        a = (a + 0x6D2B79F5) & _U32
        t = ((a ^ (a >> 15)) * (1 | a)) & _U32
        t = ((t + (((t ^ (t >> 7)) * (61 | t)) & _U32)) & _U32) ^ t
        return ((t ^ (t >> 14)) & _U32) / 4294967296

    return next_float


def random_day(rand: Callable[[], float]) -> dict[str, Any]:
    # The order of rand() calls follows the Node code exactly.
    def pick(items: list[str]) -> str:
        return items[int(rand() * len(items))]

    def rint(lo: int, hi: int) -> int:
        return lo + int(rand() * (hi - lo + 1))

    def quarter(lo: int, hi: int) -> int:  # times on 15-minute steps (lo, hi are multiples of 15)
        return rint(lo // 15, hi // 15) * 15

    work_start = quarter(6 * 60, 10 * 60)
    work_end = quarter(work_start + 4 * 60, 21 * 60)
    d_start = quarter(work_start, work_end - 30)
    # About 1 in 4 windows crosses midnight (e.g. 18:00–02:00), to test clipping.
    crosses_midnight = rand() < 0.25
    d_end = quarter(0, 4 * 60) if crosses_midnight else quarter(d_start + 15, min(d_start + 6 * 60, 23 * 60))

    protected_blocks = []
    for i in range(rint(0, 3)):
        start = quarter(work_start, work_end - 15)
        end = min(start + quarter(15, 90), 23 * 60 + 45)
        protected_blocks.append({"id": f"p{i}", "label": "Block", "start": to_hhmm(start), "end": to_hhmm(end)})
    if rand() < 0.3:
        protected_blocks.append({"id": "sleep", "label": "Sleep", "start": "22:00", "end": "06:00"})

    tasks = []
    for i in range(rint(1, 8)):
        task_type = pick(["Digital", "Analog"])
        priority = pick(["High", "Medium", "Low"])
        hours = rint(1, 16) * 0.25
        day = rint(0, 5)
        tasks.append({
            "id": f"t{i}",
            "title": f"Task {i}",
            "type": task_type,
            "priority": priority,
            "estimatedHours": hours,
            "deadline": f"2026-10-{7 + day:02d}T{pick(['12:00', '17:00', '23:59'])}",
            "delegable": rand() < 0.3,
        })

    plan_from = to_hhmm(work_start if rand() < 0.7 else quarter(work_start, work_end))
    return {
        "date": "2026-10-07",
        "workHours": {"start": to_hhmm(work_start), "end": to_hhmm(work_end)},
        "planFrom": plan_from,
        # Both kinds: environment (EF-based) and unavailable (time taken, Task 2a).
        # connectivity_failure is left out while its EF values are still None.
        "disruption": {
            "type": pick(["power_outage", "transport_delay", "urgent_work", "family_obligation", "health_issue"]),
            "start": to_hhmm(d_start),
            "end": to_hhmm(d_end),
        },
        "protectedBlocks": protected_blocks,
        "tasks": tasks,
    }


def _days() -> list[dict[str, Any]]:
    rand = seeded_random(SEED)
    return [random_day(rand) for _ in range(DAYS)]


def _js_json(value: Any) -> Any:
    """JSON as JS writes it: 2.0 → 2 (keys are sorted by json.dumps)."""
    if isinstance(value, float) and value.is_integer():
        return int(value)
    if isinstance(value, list):
        return [_js_json(v) for v in value]
    if isinstance(value, dict):
        return {k: _js_json(v) for k, v in value.items()}
    return value


def test_same_days_as_node():
    text = json.dumps(_js_json(_days()), sort_keys=True, separators=(",", ":"))
    assert hashlib.sha256(text.encode("utf-8")).hexdigest() == NODE_DAYS_SHA256


def test_mulberry32_matches_node_bit_for_bit():
    # First three values of the Node seededRandom(20261007), printed by node on 13 Oct 2026.
    rand = seeded_random(SEED)
    assert [rand(), rand(), rand()] == [0.9620683940593153, 0.42478258069604635, 0.051436981651932]


def test_ptvr_zero_and_all_hard_rules_hold_for_every_day():
    failures = []
    for i, day in enumerate(_days()):
        mvd = generate_mvd(day)
        problems = find_violations(mvd, day)
        if compute_ptvr(mvd, day) != 0 or problems:
            failures.append({"day": i, "problems": problems})
    assert failures == []
